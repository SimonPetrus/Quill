import Foundation
import UIKit.UIGraphicsImageRenderer

/// Our own manifest service (Cloudflare Worker, see `manifest-worker/`).
enum ManifestService {
	static let genPlistURL = "https://quill-manifest.quill-sign.workers.dev/genPlist"
	
	static var host: String { URL(string: genPlistURL)?.host ?? "?" }
}

extension ServerInstaller {
	var plistEndpoint: URL {
		var comps = URLComponents()
		comps.scheme = self.getServerMethod() == 1 ? "http" : "https"
		comps.host = sni()
		comps.path = "/\(id).plist"
		comps.port = port
		return comps.url!
	}

	var payloadEndpoint: URL {
		var comps = URLComponents()
		comps.scheme = self.getServerMethod() == 1 ? "http" : "https"
		comps.host = sni()
		comps.path = "/\(id).ipa"
		comps.port = port
		return comps.url!
	}
	
	/// Payload URL put into the external manifest. Always the IPv4 loopback literal: the install
	/// daemon runs on this device and the Semi Local server listens on 0.0.0.0, so loopback is
	/// reachable regardless of `sni()` (which returns the LAN address while "IP fix" is off).
	/// The manifest service only accepts loopback fetch URLs.
	var externalPayloadEndpoint: URL {
		var comps = URLComponents()
		comps.scheme = self.getServerMethod() == 1 ? "http" : "https"
		comps.host = "127.0.0.1"
		comps.path = "/\(id).ipa"
		comps.port = port
		return comps.url!
	}
	
	var pageEndpoint: URL {
		var comps = URLComponents()
		comps.scheme = self.getServerMethod() == 1 ? "http" : "https"
		comps.host = sni()
		comps.path = "/install"
		comps.port = port
		return comps.url!
	}
	
	var externalServerLink: String {
		// Each value is encoded on its own with a strict set (only unreserved characters stay),
		// so `&`, `=`, `+`, `#`, `?`, spaces and non-ASCII characters in the app name cannot split or corrupt the query.
		var strict = CharacterSet(charactersIn: "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-._~")
		strict.remove(charactersIn: "+&=#?")
		func enc(_ value: String) -> String {
			value.addingPercentEncoding(withAllowedCharacters: strict) ?? ""
		}
		
		let baseUrl = "\(ManifestService.genPlistURL)?bundleid=\(enc(app.identifier!))&name=\(enc(app.name!))&version=\(enc(app.version!))&fetchurl=\(enc(self.externalPayloadEndpoint.absoluteString))"
		// Outer encoding for the itms-services `url=` value; iOS decodes it once, leaving the inner encoding intact.
		return baseUrl.addingPercentEncoding(withAllowedCharacters: .alphanumerics)!
	}

	var iTunesLink: String {
		_iTunesLink(with: plistEndpoint.absoluteString)
	}
	
	var iTunesLinkExternal: String {
		_iTunesLink(with: externalServerLink)
	}
	
	private func _iTunesLink(with url: String) -> String {
		return "itms-services://?action=download-manifest&url=\(url)"
	}

	var displayImageSmallEndpoint: URL {
		var comps = URLComponents()
		comps.scheme = "https"
		comps.host = sni()
		comps.path = "/app57x57.png"
		comps.port = port
		return comps.url!
	}

	var displayImageLargeEndpoint: URL {
		var comps = URLComponents()
		comps.scheme = "https"
		comps.host = sni()
		comps.path = "/app512x512.png"
		comps.port = port
		return comps.url!
	}
	
	var displayImageSmallData: Data {
		_createIcon(57)
	}
	
	var displayImageLargeData: Data {
		_createIcon(512)
	}
	
	private func _createIcon(_ r: CGFloat) -> Data {
		let renderer = UIGraphicsImageRenderer(size: .init(width: r, height: r))
		let image = renderer.image { ctx in
			UIColor.tintColor.setFill()
			ctx.fill(.init(x: 0, y: 0, width: r, height: r))
		}
		return image.pngData()!
	}

	var html: String {
		"""
		<html style="background-color: black;">
		<script type="text/javascript">window.location="\(iTunesLinkExternal)"</script>
		</html>
		"""
	}

	var installManifest: [String: Any] {[
		"items": [[
			"assets": [
				[
					"kind": "software-package",
					"url": payloadEndpoint.absoluteString,
				],
				[
					"kind": "display-image",
					"url": displayImageSmallEndpoint.absoluteString,
				],
				[
					"kind": "full-size-image",
					"url": displayImageLargeEndpoint.absoluteString,
				],
			],
			"metadata": [
				"bundle-identifier": app.identifier,
				"bundle-version": app.version,
				"kind": "software",
				"title": app.name,
			],
		],],
	]}

	var installManifestData: Data {
		(try? PropertyListSerialization.data(
			fromPropertyList: installManifest,
			format: .xml,
			options: .zero
		)) ?? .init()
	}
}
